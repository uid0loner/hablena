const v = (inf, en, de, extra = {}) => ({ inf, en, de, ...extra });

// Compounds inherit every irregularity of their base verb, with the prefix added.
// A monosyllabic tú-imperative gains an accent: ten → mantén, pon → propón.
const ACCENT = { a: 'á', e: 'é', i: 'í', o: 'ó', u: 'ú' };
function compound(prefix, base, inf, en, de) {
  const p = (s) => (s ? prefix + s : undefined);
  const out = { inf, en, de };
  if (base.sc) out.sc = base.sc;
  if (base.yo) out.yo = p(base.yo);
  if (base.strong) out.strong = p(base.strong);
  if (base.hizo) out.hizo = p(base.hizo);
  if (base.fut) out.fut = p(base.fut);
  if (base.part) out.part = p(base.part);
  if (base.impTu) {
    const t = base.impTu;
    const accented = /^[^aeiou]*[aeiou][^aeiou]*$/.test(t) && /[ns]$|[aeiou]$/.test(t)
      ? t.replace(/[aeiou](?=[^aeiou]*$)/, (m) => ACCENT[m])
      : t;
    out.impTu = prefix + accented;
  }
  return out;
}

